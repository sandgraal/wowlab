"""Check a copy of the wiki before anything is pushed to it (M12-14).

    uv run python scripts/check_wiki.py DIR [--base REF]

DIR is a checkout of `<repository>.wiki.git`. The daily wiki job pushes with
no pull request, so this check is what stands between a bad run and a public
page, and it fails closed: exit 1 with one line per failure, exit 0 with one
summary line when there is none.

What it checks:

- every internal link (`[text](Page)`, `[text](Page#anchor)`, `[[Page]]`,
  reference definitions) on every page, `_Sidebar` included, names a page that
  exists, and an anchor names a heading on that page;
- every `wowlab ...` invocation in code (a code span or a fenced line that
  starts with `wowlab`, `uv run wowlab` or `$ wowlab`) names a command that
  exists in the Click tree, and every option in it is one that command has.
  Placeholders (`<group>`, `COMMAND`, `…`) end the check of that invocation;
  `Usage:` lines never start with `wowlab`, so they are not invocations;
- every leaf command and every public module of `wowlab_core` is named or
  linked on at least one hand-written page (the generated page names every
  command by construction, so it does not count);
- the generated page (`CLI-Reference.md`) exists and is byte for byte what
  `scripts/gen_command_reference.py` renders now: nobody edits it by hand;
- the wiki holds only top-level `*.md` pages and the job's `.lab/state.json`;
- nothing matches an absolute home path, an install path other than the
  documented default locations (`wowlab_core.install.default_roots`), a
  numeric account folder, a `Name-Realm` pair other than the documented
  placeholders, an email address, a BattleTag or a credential-shaped string;
- with `--base REF` (a commit in DIR): the change against REF stays under a
  fixed size cap, so no single run can rewrite the wiki, and adds no link to
  a host the wiki at REF does not already link to.

A failure that quotes personal data names only the page, the line and the
kind of match: the job log and the failure issue are public.

Reads DIR (and its git objects, with `git show`); writes nothing.
"""

