"""Check a copy of the wiki before anything is pushed to it (M12-14).

    uv run python scripts/check_wiki.py DIR [--base REF]

DIR is a checkout of `<repository>.wiki.git`. The daily wiki job pushes with
no pull request, so this check is what stands between a bad run and a public
page, and it fails closed. Exit codes: 0 no failure (one summary line);
1 failures, none of them personal data; 3 failures, at least one of them
personal data (the job then withholds its artifacts); 2 a usage or git error.
One line per failure.

What it checks:

- every internal link (`[text](Page)`, `[text](Page#anchor)`, `[[Page]]`,
  reference definitions) on every page, `_Sidebar` included, names a page that
  exists, and an anchor names a heading on that page (GitHub's slugs);
- every `wowlab ...` invocation in code (each command of a code span or a
  fenced line, split at `&&`, `||`, `|`, `\\|` and `;`, that starts with
  `wowlab`, `uv run wowlab` or `$ wowlab`) names a command that exists in
  the Click tree, and every option in it is one that command has.
  Placeholders (`<group>`, `COMMAND`, `…`) end the check of that invocation;
- every leaf command and every public module of `wowlab_core` is named or
  linked on at least one hand-written page (the generated page names every
  command by construction, so it does not count);
- the generated page (`CLI-Reference.md`) exists and is byte for byte what
  `scripts/gen_command_reference.py` renders now: nobody edits it by hand;
- the wiki holds only top-level `*.md` pages and the job's `.lab/state.json`;
  no page is named `CLAUDE.md`, and no two page names differ only in case or
  in a space versus a hyphen;
- no link has a scheme other than http or https, and no page holds raw HTML
  with a URL attribute (`href`, `src`, ...);
- nothing, in any file's text or any file name, matches an absolute home
  path, an install path other than the documented default locations
  (`wowlab_core.install.default_roots`), a numeric account folder, a
  `Name-Realm` pair other than the documented placeholders and the reviewed
  terms in `scripts/wiki_allowed_terms.txt`, an email address, a BattleTag
  or a credential-shaped string. Text is matched after HTML entities and
  Markdown escapes are decoded, NFKC normalisation, and removal of zero-width
  and other format characters;
- with `--base REF` (a commit in DIR): the change against REF stays under a
  fixed size cap, so no single run can rewrite the wiki, and no link goes to
  a host the wiki at REF does not already link to (Markdown links, reference
  definitions, protocol-relative links, `https://` and `www.` autolinks).

No failure line quotes text taken from a page or a file name unless that
text first passed the personal-data matchers; otherwise it names only the
kind. The job log, its artifacts and the failure issue are public.

Reads DIR (and its git objects, with `git show`); writes nothing.
"""

