"""`wowlab_core.clientlists` (M22-18): the client's slash commands, key-binding
commands and encoding limits, shipped in the package.

The lists are generated by `scripts/forever_api.py` from pinned commits of
Gethe/wow-ui-source and Ketho/BlizzardInterfaceResources (its tests,
`tests/scripts/test_forever_api.py`, grade the reading). Here the shipped
lists are graded against the real captures: every binding command a real
lab-addon record or `bindings-cache.wtf` holds is in the binding list but the
two addons' commands the owner had bound, and every `/command` of a real
`macros-cache.txt` is in the slash list. Inputs labelled `constructed` are
malformed list files (L8). Nothing here opens an install.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from wowlab_core import clientlists, keymap, labaddon, macrocheck, wtfconfig

FIXTURES = Path(__file__).resolve().parent / "fixtures"
SOURCE = Path(clientlists.__file__).read_text(encoding="utf-8")
# The two addons' binding commands bound in the real captures (Questie's
# journey window, and a command no Blizzard file defines).
ADDON_COMMANDS = {"ITEMTREE_OPEN", "QUESTIE_TOGGLE_JOURNEY"}


def _records() -> list[Path]:
    return sorted(FIXTURES.rglob("WowLab.lua"))


def _record_commands(path: Path) -> set[str]:
    try:
        record = labaddon.read_char(path)
    except labaddon.LabAddonError:
        return set()  # an account file
    binds = getattr(record, "bindings", None)
    if not isinstance(binds, labaddon.Bindings):
        return set()
    return {b.command for b in binds.list_}


def test_the_shipped_lists_name_their_build_and_hold_the_documented_limits() -> None:
    lists = clientlists.lists()
    assert lists.ui_build == "1.60.1.71037"
    assert lists.ui_commit == "734f065329cff4992835b01a84f210a297db91b6"
    assert lists.strings_build == "1.60.1.70938"
    assert clientlists.encoding_limits() == {
        "EncodingDecompressSizeLimit": 104857600,
        "EncodingDeserializeSizeLimit": 104857600,
        "EncodingStackSizeLimit": 100,
    }
    assert len(lists.bindings) > 300 and len(lists.slash) > 4000


def test_every_binding_command_of_the_real_records_is_the_clients_but_two_addons() -> None:
    seen: set[str] = set()
    for path in _records():
        seen |= _record_commands(path)
    assert len(seen) > 120, "the schema-3 to schema-5 records hold the bindings section"
    unknown = {c for c in seen if clientlists.binding_command(c) is None}
    assert unknown == ADDON_COMMANDS


def test_every_command_of_the_real_bindings_files_is_the_clients_but_two_addons() -> None:
    seen: set[str] = set()
    for path in sorted(FIXTURES.rglob("bindings-cache.wtf")):
        seen |= {b.action for b in wtfconfig.read_bindings(path).bindings}
    unknown = {c for c in seen if clientlists.binding_command(c) is None}
    assert unknown == ADDON_COMMANDS | {"NONE"}


def test_every_slash_command_of_the_real_macros_is_the_clients() -> None:
    seen: set[str] = set()
    for path in sorted(FIXTURES.rglob("macros-cache.txt")):
        for macro in wtfconfig.read_macros(path).macros:
            for line in macro.body_lines:
                if (match := re.match(r"\s*(/[^\s\[\]]+)", line)) is not None:
                    seen.add(match.group(1))
    # 70888's character file: /cast, /use, /kneel and /dance (two emotes);
    # the 69913 capture's /castsequence.
    assert {"/cast", "/use", "/kneel", "/dance", "/castsequence"} <= seen
    assert [c for c in seen if clientlists.slash_command(c) is None] == []
    assert clientlists.slash_command("/dance").source == "emote"  # type: ignore[union-attr]


def test_the_names_the_library_relies_on_are_the_clients() -> None:
    """The chat commands `macrocheck` treats as free text, and the action
    button, pet, stance and page commands `keymap` reads, are in the
    client's lists, but for three chat commands written from memory that
    no client string names at this build (a finding, left as it is: the
    bracket rule only reads them as free text)."""
    missing = {c for c in macrocheck.CHAT_COMMANDS if clientlists.slash_command(c) is None}
    assert missing == {"/bn", "/print", "/raidwarning"}
    for prefix in keymap.BAR_PAGES:
        for button in range(1, 13):
            assert clientlists.binding_command(f"{prefix}{button}") is not None, prefix
    for n in range(1, 11):
        assert clientlists.binding_command(f"BONUSACTIONBUTTON{n}") is not None
        assert clientlists.binding_command(f"SHAPESHIFTBUTTON{n}") is not None
    for n in range(1, 7):
        assert clientlists.binding_command(f"ACTIONPAGE{n}") is not None


def test_a_command_is_found_whatever_its_case() -> None:
    upper = clientlists.slash_command("/CAST")
    assert upper is not None and (upper.text, upper.source, upper.key) == (
        "/cast",
        "registered",
        "CAST",
    )
    assert clientlists.slash_command("/1") is not None
    assert clientlists.slash_command("/20") is not None
    assert clientlists.slash_command("/21") is None
    assert clientlists.slash_command("/questie") is None
    world = clientlists.binding_command("TOGGLEWORLDMAP")
    assert world is not None
    assert (world.label, world.category, world.category_label) == (
        "Toggle World Map Pane",
        "BINDING_HEADER_INTERFACE",
        "Interface Panel",
    )
    assert clientlists.binding_command("toggleworldmap") is None  # commands are upper case


def test_the_library_names_no_build_and_no_flavor() -> None:
    """L6: the build is read from the lists' header, never written in code."""
    assert re.search(r"\d\.\d+\.\d\.\d{5}|7\d{4}|_forever_|_classic_|camelot", SOURCE, re.I) is None


# ─── the language and the build (review round 1) ─────────────────────────────


def test_a_language_narrows_the_slash_list_to_it_and_english() -> None:
    """`/wirken` is German for /cast: found with no language and with
    deDE, not for an English client. `/em` is the emote chat type in English
    and another command in Portuguese: each language gets its own."""
    assert clientlists.slash_command("/wirken") is not None
    assert clientlists.slash_command("/wirken", "deDE") is not None
    assert clientlists.slash_command("/wirken", "enUS") is None
    english = clientlists.slash_command("/em", "enUS")
    assert english is not None and english.key == "EMOTE"
    union = clientlists.slash_command("/em")
    assert union is not None and union.key == "EMOTE"  # the English one wins the union
    portuguese = clientlists.slash_command("/em", "ptBR")
    assert portuguese is not None and portuguese.key == "SUMMON_BATTLE_PET"
    # English texts count on every client.
    assert clientlists.slash_command("/cast", "koKR") is not None
    assert clientlists.languages_words(None).startswith("in any client language")
    assert clientlists.languages_words("deDE") == "in English or this install's language, deDE"


def test_the_lists_judge_only_their_own_patch_and_name_both_builds() -> None:
    assert clientlists.source_words() == "interface code 1.60.1.71037, strings 1.60.1.70938"
    assert clientlists.mismatch(None) is None
    # Every real capture's build (69913 to 71037) is patch 1.60.1.
    assert clientlists.mismatch(clientlists.Client(build="1.60.1.69913")) is None
    why = clientlists.mismatch(clientlists.Client(build="1.61.0.72000"))  # constructed
    assert why == (
        "the game's command lists were read at interface code 1.60.1.71037, strings "
        "1.60.1.70938, and this client is 1.61.0.72000"
    )
    unknown = clientlists.mismatch(clientlists.Client(build=None))
    assert unknown is not None and unknown.endswith("this client's build is not known")


# ─── constructed list files ──────────────────────────────────────────────────

HEAD = "# ui-build: 9.9.9.1\n# ui-commit: abc\n# strings-build: 9.9.9.0\n\n"
ROW = "/x\tregistered\tX\t*\n"


def _parse(
    slash: str = ROW, bind: str = "X\t\t\t\tf.xml\n", limit: str = "L\t1\tsize\n"
) -> clientlists.ClientLists:
    return clientlists.parse(HEAD + slash, HEAD + bind, HEAD + limit)


def test_constructed_lists_parse_with_empty_labels_as_none() -> None:
    parsed = _parse(slash=ROW + "/x\tnamed\tY\tdeDE,frFR\n")
    assert parsed.ui_build == "9.9.9.1"
    assert parsed.bindings["X"] == clientlists.BindingCommand(
        name="X", category=None, category_label=None, label=None, file="f.xml"
    )
    assert [(e.key, e.languages) for e in parsed.slash["/x"]] == [
        ("X", None),
        ("Y", ("deDE", "frFR")),
    ]
    assert parsed.limits == {"L": 1}


@pytest.mark.parametrize(
    ("kwargs", "message"),
    [
        ({"slash": "/x\tregistered\tX\n"}, "3 columns, not 4"),
        ({"slash": "x\tregistered\tX\t*\n"}, "not a slash command"),
        ({"slash": "/x\tsomewhere\tX\t*\n"}, "not a slash command"),
        ({"slash": "/x\tregistered\tX\tgerman\n"}, "has the languages 'german'"),
        ({"bind": "lower\t\t\t\tf.xml\n"}, "not a command name"),
        ({"limit": "L\tmany\tsize\n"}, "L = 'many'"),
        ({"limit": ""}, "no line"),
    ],
    ids=lambda value: "constructed" if isinstance(value, dict) else str(value)[:20],
)
def test_constructed_malformed_lists_are_refused(kwargs: dict[str, str], message: str) -> None:
    with pytest.raises(clientlists.ClientListsError, match=re.escape(message)):
        _parse(**kwargs)


def test_constructed_lists_of_different_builds_are_refused() -> None:
    other = HEAD.replace("9.9.9.1", "9.9.9.2")
    with pytest.raises(clientlists.ClientListsError, match="different ui-builds"):
        clientlists.parse(HEAD + ROW, other + "X\t\t\t\tf\n", HEAD + "L\t1\ts\n")
    with pytest.raises(clientlists.ClientListsError, match="no ui-build line"):
        clientlists.parse(ROW, HEAD + "X\t\t\t\tf\n", HEAD + "L\t1\ts\n")
