"""`toc` header reading of an oversized TOC (M22-21; constructed, L8).

Every input here is constructed and labelled `constructed`: no committed
TOC is larger than the read limit, and the real one that is (QuestieDB's
Forever TOC, 18,902,713 bytes in the owner's install) is checked by the
owner-run `@live` test in `test_toc_oversized_live.py`. The shape copied
from it: directives and comments, a blank, the file lines, a blank, then
`## X-` lines of base64 data running far past the limit.
"""

from __future__ import annotations

import base64
from pathlib import Path

import pytest

from wowlab_core.toc import (
    MAX_TOC_BYTES,
    Directive,
    FileLine,
    TocDocument,
    TocTooLargeError,
    parse_toc,
    parse_toc_header,
    read_toc,
)

HEADER = (
    b"## Interface: 16001\n"
    b"# GENERATED by a build script. Do not edit.\n"
    b"## Title: Big|cFF00FF00 v1.1.5|r\n"
    b"## Version: 1.1.5\n"
    b"## Dependencies: LibA, LibB\n"
    b"## X-Flavor: Forever\n"
    # An `X-` key that ends in a dependency directive's name, and a value
    # that spells one: neither is a dependency field.
    b"## X-Dependencies: NotA, NotB\n"
    b"## X-Blob-1: " + base64.b64encode(b"## Dependencies: Evil\n" * 3) + b"\n"
    b"\n"
)
FILES = b"src\\config.lua\nsrc\\read\\baked.lua\n\n"


def _blob(n: int) -> bytes:
    """`n` `## X-` lines of base64, about 1 KiB each, like QuestieDB's."""
    payload = base64.b64encode(bytes(range(256)) * 3)
    return b"".join(b"## X-l10n-Object-%d: %s\n" % (i, payload) for i in range(n))


def _big(tmp_path: Path, data: bytes) -> Path:
    path = tmp_path / "Big_Forever.toc"
    path.write_bytes(data)
    return path


@pytest.mark.parser
def test_an_oversized_toc_gives_its_header_constructed(tmp_path: Path) -> None:
    data = HEADER + FILES + _blob(1_200)
    assert len(data) > MAX_TOC_BYTES, "past the default limit, which is not raised"
    path = _big(tmp_path, data)
    with pytest.raises(TocTooLargeError):
        read_toc(path)
    doc = read_toc(path, oversized="header")
    assert doc.partial is True
    assert doc.to_bytes() == HEADER, "every header line kept, byte for byte; no file line"
    assert doc.interface is not None and doc.interface.versions == (16001,)
    assert doc.get("Title") == "Big|cFF00FF00 v1.1.5|r"
    assert doc.get("Version") == "1.1.5"
    assert doc.list_value("Dependencies") == ("LibA", "LibB")
    assert doc.list_value("RequiredDeps") == ()
    assert doc.get("X-Dependencies") == "NotA, NotB"
    assert doc.files == ()
    assert len(doc.comments) == 1
    assert doc.decode_errors is False


@pytest.mark.parser
def test_x_lines_before_the_files_do_not_end_the_header_constructed(tmp_path: Path) -> None:
    """A header made mostly of `## X-` lines is read through them to the
    first file line."""
    head = b"## Interface: 16001\n" + _blob(50) + b"## Version: 2\n"
    data = head + FILES + _blob(1_200)
    doc = read_toc(_big(tmp_path, data), oversized="header")
    assert doc.to_bytes() == head
    assert doc.get("Version") == "2"
    assert sum(1 for d in doc.directives if d.key.startswith("X-")) == 50


@pytest.mark.parser
def test_a_header_longer_than_the_limit_keeps_whole_lines_only_constructed(
    tmp_path: Path,
) -> None:
    """With no file line within the limit, the header is cut at the limit,
    and the line the cut falls in is dropped whole, never kept in part."""
    data = HEADER + _blob(1_200) + FILES
    doc = read_toc(_big(tmp_path, data), oversized="header")
    kept = doc.to_bytes()
    assert doc.partial is True
    assert len(kept) <= MAX_TOC_BYTES
    assert data.startswith(kept) and kept.endswith(b"\n")
    assert data[len(kept) : MAX_TOC_BYTES].find(b"\n") == -1, "only the cut line was dropped"
    assert doc.get("Version") == "1.1.5"
    assert doc.files == ()


@pytest.mark.parser
@pytest.mark.parametrize(
    ("data", "cut", "kept"),
    [
        (b"## Title: A\r\n## Version: 1\r\nA.lua\r\n", 27, b"## Title: A\r\n"),
        (b"## Title: A\r\n## Version: 1\r\nA.lua\r\n", 28, b"## Title: A\r\n## Version: 1\r\n"),
        (b"## Title: A\n## Version: 1\n", 26, b"## Title: A\n## Version: 1\n"),
        (b"## Title: A\n## Version: 1\n", 25, b"## Title: A\n"),
        (b"## Title: A\nA.lua\n## Version: 1\n", 30, b"## Title: A\n"),
        (b"no break at all " * 4, 40, b""),
    ],
    ids=[
        "constructed-cut-between-cr-and-lf",
        "constructed-cut-after-crlf",
        "constructed-cut-at-a-line-break",
        "constructed-cut-before-a-line-break",
        "constructed-directive-after-a-file-line-unseen",
        "constructed-no-line-break-within-the-limit",
    ],
)
def test_header_cut_points_constructed(data: bytes, cut: int, kept: bytes) -> None:
    doc = parse_toc_header(data[:cut])
    assert doc.partial is True
    assert doc.to_bytes() == kept
    assert not any(isinstance(line, FileLine) for line in doc.lines)


@pytest.mark.parser
def test_a_bom_is_kept_and_invalid_utf8_in_the_header_is_flagged_constructed() -> None:
    doc = parse_toc_header(b"\xef\xbb\xbf## Title: \xff\nA.lua\n## X: 1\n")
    assert doc.bom is True
    assert doc.to_bytes() == b"\xef\xbb\xbf## Title: \xff\n"
    assert doc.decode_errors is True
    clean = parse_toc_header(b"## Title: T\nA.lua\n\xff\xfe\n")
    assert clean.decode_errors is False, "only the bytes kept are judged"


@pytest.mark.parser
def test_a_toc_within_the_limit_is_read_whole_either_way_constructed(tmp_path: Path) -> None:
    data = HEADER + FILES + b"## X-After: 1\n"
    path = _big(tmp_path, data)
    whole = read_toc(path, oversized="header")
    assert whole.partial is False
    assert whole.to_bytes() == data, "a whole file stays lossless (L4)"
    assert whole == parse_toc(data) == read_toc(path)
    assert whole.get("X-After") == "1"


@pytest.mark.parser
def test_the_read_stops_at_the_limit_constructed(tmp_path: Path) -> None:
    """A file many times the limit, with no file line at all: what is kept
    is within the limit and ends at a line break."""
    data = HEADER + _blob(20_000)  # about 20 MiB
    doc = read_toc(_big(tmp_path, data), oversized="header")
    kept = doc.to_bytes()
    assert len(kept) <= MAX_TOC_BYTES and data.startswith(kept) and kept.endswith(b"\n")
    assert doc.files == ()
    assert isinstance(doc.lines[0], Directive) and doc.lines[0].key == "Interface"


@pytest.mark.parser
def test_a_partial_document_round_trips_through_json_constructed() -> None:
    doc = parse_toc_header(HEADER + FILES)
    assert TocDocument.model_validate_json(doc.model_dump_json()) == doc
    assert '"partial":true' in doc.model_dump_json()
